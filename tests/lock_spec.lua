local T = require('nvim_kit.test')
local lock = require('nvim_kit.lock')

local uv = vim.uv or vim.loop

local function tmp_lock()
  local dir = vim.fn.tempname()
  vim.fn.mkdir(dir, 'p')
  return dir .. '/index.lock', dir
end

local function age_by(path, seconds)
  local t = os.time() - seconds
  assert(uv.fs_utime(path, t, t))
end

local function autocmds()
  return #vim.api.nvim_get_autocmds({ event = 'VimLeavePre' })
end

T.case('acquire writes "<pid> <ISO time>" and release removes the file', function()
  local p, dir = tmp_lock()
  local h = assert(lock.acquire(p))
  local text = table.concat(vim.fn.readfile(p), '\n')
  T.ok(text:match('^' .. uv.os_getpid() .. ' %d%d%d%d%-%d%d%-%d%dT%d%d:%d%d:%d%d$'), text)
  h.release()
  T.eq(uv.fs_stat(p), nil)
  vim.fn.delete(dir, 'rf')
end)

T.case('a second acquire is refused with the age, until release', function()
  local p, dir = tmp_lock()
  local h = assert(lock.acquire(p))
  local h2, err = lock.acquire(p)
  T.eq(h2, nil)
  T.eq(err.error, 'locked')
  T.eq(type(err.detail), 'number')
  T.ok(err.detail >= 0 and err.detail < 5, vim.inspect(err))
  h.release()
  local h3 = assert(lock.acquire(p))
  h3.release()
  vim.fn.delete(dir, 'rf')
end)

T.case('a lock older than the limit is taken over', function()
  local p, dir = tmp_lock()
  vim.fn.writefile({ '99999 2000-01-01T00:00:00' }, p)
  age_by(p, 3600)
  local h = lock.acquire(p)
  T.ok(h, 'taken over')
  T.ok(table.concat(vim.fn.readfile(p), ''):find('^' .. uv.os_getpid() .. ' '), 'now ours')
  h.release()
  T.eq(uv.fs_stat(p), nil)
  vim.fn.delete(dir, 'rf')
end)

T.case('stale_after_s decides: age 5 s with a limit of 10 s is still locked', function()
  local p, dir = tmp_lock()
  vim.fn.writefile({ '99999 x' }, p)
  age_by(p, 5)
  local h, err = lock.acquire(p, { stale_after_s = 10 })
  T.eq(h, nil)
  T.eq(err.error, 'locked')
  T.ok(err.detail >= 4 and err.detail <= 8, vim.inspect(err))
  T.eq(vim.fn.readfile(p), { '99999 x' })
  local h2 = lock.acquire(p, { stale_after_s = 2 })
  T.ok(h2, 'age 5 s is stale against a 2 s limit')
  h2.release()
  vim.fn.delete(dir, 'rf')
end)

T.case('the default limit is 1800 s', function()
  local p, dir = tmp_lock()
  vim.fn.writefile({ '99999 x' }, p)
  age_by(p, 1700)
  T.eq(select(2, lock.acquire(p)).error, 'locked')
  age_by(p, 1900)
  local h = lock.acquire(p)
  T.ok(h)
  h.release()
  vim.fn.delete(dir, 'rf')
end)

T.case('release twice is fine and does not delete a later lock', function()
  local p, dir = tmp_lock()
  local h = assert(lock.acquire(p))
  h.release()
  h.release()
  local h2 = assert(lock.acquire(p))
  h.release() -- the old handle must not remove the new holder's lock
  T.ok(uv.fs_stat(p), 'the second holder still has its lock')
  h2.release()
  T.eq(uv.fs_stat(p), nil)
  vim.fn.delete(dir, 'rf')
end)

T.case('a holder whose lock went stale and was taken over does not delete the new lock', function()
  local p, dir = tmp_lock()
  local old = assert(lock.acquire(p))
  age_by(p, 3600)
  local new = assert(lock.acquire(p)) -- takes over
  old.release()
  T.ok(uv.fs_stat(p), 'the new holder keeps its lock')
  T.eq(select(2, lock.acquire(p)).error, 'locked')
  new.release()
  T.eq(uv.fs_stat(p), nil)
  vim.fn.delete(dir, 'rf')
end)

T.case('acquire creates the parent directory', function()
  local base = vim.fn.tempname()
  local p = base .. '/x/y/index.lock'
  local h = assert(lock.acquire(p))
  T.ok(uv.fs_stat(p))
  h.release()
  vim.fn.delete(base, 'rf')
end)

T.case('release removes the VimLeavePre autocmd, so handles do not accumulate', function()
  local p, dir = tmp_lock()
  local before = autocmds()
  local h = assert(lock.acquire(p))
  T.eq(autocmds(), before + 1)
  h.release()
  T.eq(autocmds(), before)
  for _ = 1, 5 do
    lock.acquire(p).release()
  end
  T.eq(autocmds(), before)
  vim.fn.delete(dir, 'rf')
end)

T.case('VimLeavePre releases a lock that was never released', function()
  local p, dir = tmp_lock()
  local h = assert(lock.acquire(p))
  vim.api.nvim_exec_autocmds('VimLeavePre', {})
  T.eq(uv.fs_stat(p), nil)
  h.release()
  vim.fn.delete(dir, 'rf')
end)

T.case('acquire refuses a path that is not a string', function()
  T.raises(function()
    lock.acquire(nil)
  end)
end)

T.case('acquire raises, not "locked", when the directory is read-only', function()
  if uv.getuid and uv.getuid() == 0 then
    io.write('SKIPPED (root: chmod does not block): read-only directory\n')
    return
  end
  local p, dir = tmp_lock()
  assert(uv.fs_chmod(dir, tonumber('555', 8)))
  local ok, err = pcall(lock.acquire, p)
  assert(uv.fs_chmod(dir, tonumber('755', 8)))
  vim.fn.delete(dir, 'rf')
  T.eq(ok, false)
  T.ok(tostring(err):find('cannot create', 1, true), tostring(err))
end)

T.case('acquire raises when the lock path is a directory', function()
  local p, dir = tmp_lock()
  vim.fn.mkdir(p, 'p')
  local ok, err = pcall(lock.acquire, p)
  T.eq(ok, false)
  T.ok(tostring(err):find('not a lock file', 1, true), tostring(err))
  age_by(p, 3600) -- an old directory must not be "taken over" either
  T.eq(pcall(lock.acquire, p), false)
  vim.fn.delete(dir, 'rf')
end)

T.case('acquire raises when a path component is a file', function()
  local _, dir = tmp_lock()
  vim.fn.writefile({ 'x' }, dir .. '/blocker')
  T.eq(pcall(lock.acquire, dir .. '/blocker/sub/index.lock'), false)
  vim.fn.delete(dir, 'rf')
end)
