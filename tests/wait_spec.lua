local T = require('nvim_kit.test')
local W = require('nvim_kit.wait')

T.case('result: returns the value the callback was given, and true', function()
  local value, answered = W.result(function(cb)
    vim.defer_fn(function()
      cb('hello')
    end, 20)
  end, 2000)
  T.eq(value, 'hello')
  T.eq(answered, true)
end)

T.case('result: a callback that answers at once (synchronously) is returned too', function()
  local value, answered = W.result(function(cb)
    cb({ n = 1 })
  end, 100)
  T.eq(value, { n = 1 })
  T.eq(answered, true)
end)

T.case('result: no answer in time gives nil, false', function()
  local t0 = vim.uv.hrtime()
  local value, answered = W.result(function() end, 80)
  local ms = (vim.uv.hrtime() - t0) / 1e6
  T.eq(value, nil)
  T.eq(answered, false)
  T.ok(ms >= 70, 'returned after ' .. ms .. ' ms')
end)

T.case('result: a callback answering nil gives nil, true', function()
  local value, answered = W.result(function(cb)
    vim.defer_fn(function()
      cb(nil)
    end, 10)
  end, 2000)
  T.eq(value, nil)
  T.eq(answered, true)
end)

T.case('result: a callback answering false gives false, true', function()
  local value, answered = W.result(function(cb)
    cb(false)
  end, 100)
  T.eq(value, false)
  T.eq(answered, true)
end)

T.case('result: a callback of an earlier timed-out call does not leak into a later call', function()
  local late
  local _, answered = W.result(function(cb)
    late = cb
  end, 20)
  T.eq(answered, false)
  local value = W.result(function(cb)
    late('too late') -- the old callback fires while the new call waits
    vim.defer_fn(function()
      cb('fresh')
    end, 10)
  end, 2000)
  T.eq(value, 'fresh')
end)

T.case('result: only the first callback argument is kept', function()
  local value, answered = W.result(function(cb)
    cb(nil, 'an error')
  end, 100)
  T.eq(value, nil)
  T.eq(answered, true)
end)

T.case("result: returns start's return value as a third value", function()
  local _, answered, handle = W.result(function()
    return { cancel = true }
  end, 20)
  T.eq(answered, false)
  T.eq(handle, { cancel = true })
end)

T.case('result: from a fast callback it raises before start runs', function()
  local started, res = false, nil
  local timer = vim.uv.new_timer()
  timer:start(0, 0, function()
    res = { pcall(W.result, function()
      started = true
    end, 10) }
  end)
  vim.wait(2000, function()
    return res ~= nil
  end, 5)
  timer:close()
  T.ok(res, 'the timer did not fire')
  T.eq(res[1], false)
  T.ok(tostring(res[2]):find('fast', 1, true), tostring(res[2]))
  T.eq(started, false)
end)

T.case('result: invalid arguments raise', function()
  T.raises(function()
    W.result('x', 10)
  end, 'start')
  T.raises(function()
    W.result(function() end, -1)
  end, 'timeout_ms')
  T.raises(function()
    W.result(function() end, '10')
  end, 'timeout_ms')
  T.raises(function()
    W.result(function() end)
  end, 'timeout_ms')
end)

T.case('result: an error in start propagates', function()
  T.raises(function()
    W.result(function()
      error('boom')
    end, 10)
  end, 'boom')
end)
